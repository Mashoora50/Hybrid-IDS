import pandas as pd
import numpy as np
import joblib, os
from sklearn.model_selection import train_test_split, RandomizedSearchCV
from sklearn.preprocessing import StandardScaler, LabelEncoder
from sklearn.metrics import classification_report, f1_score, accuracy_score, confusion_matrix, ConfusionMatrixDisplay
import xgboost as xgb
from imblearn.over_sampling import SMOTE
import matplotlib.pyplot as plt

DATA_PATH = "/content/drive/MyDrive/masters_thesis/notebook/xgboost_reduced.parquet"
df = pd.read_parquet(DATA_PATH)
print("Shape:", df.shape)
print(df["label"].value_counts())

LEAKY_FEATURES = ["day_of_week", "hour", "timestamp"]
drop_cols = [c for c in LEAKY_FEATURES if c in df.columns]
print("Dropping:", drop_cols)

feature_cols = [c for c in df.columns if c not in ["label", "label_encoded"] + LEAKY_FEATURES]
print("Feature count (no leakage):", len(feature_cols))
print(feature_cols)

X = df[feature_cols].values
y = df["label_encoded"].values

import time

RANDOM_STATE = 42

X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.2, random_state=RANDOM_STATE, stratify=y
)

scaler = StandardScaler()
X_train_s = scaler.fit_transform(X_train)
X_test_s = scaler.transform(X_test)

print("Before SMOTE:", pd.Series(y_train).value_counts().to_dict())

train_counts = pd.Series(y_train).value_counts()
majority_count = train_counts.max()
target_ratio = 0.25

sampling_strategy = {
    cls: int(majority_count * target_ratio)
    for cls, count in train_counts.items()
    if count < majority_count * target_ratio
}
print("SMOTE targets:", sampling_strategy)

smote = SMOTE(random_state=RANDOM_STATE, sampling_strategy=sampling_strategy)

print("Starting SMOTE.")
print("there's no progress bar for this step.")
start = time.time()

X_train_sm, y_train_sm = smote.fit_resample(X_train_s, y_train)

elapsed = time.time() - start
print(f"SMOTE finished in {elapsed/60:.1f} minutes")
print("After SMOTE: ", pd.Series(y_train_sm).value_counts().to_dict())
print("Resampled training set size:", X_train_sm.shape)

from sklearn.preprocessing import LabelEncoder

# Instantiate and fit label_encoder to get class names
label_encoder = LabelEncoder()
label_encoder.fit(df["label"])

baseline_model = xgb.XGBClassifier(
    n_estimators=300,
    max_depth=8,
    learning_rate=0.1,
    objective="multi:softprob",
    num_class=len(label_encoder.classes_),
    eval_metric="mlogloss",
    tree_method="hist",
    random_state=RANDOM_STATE,
    n_jobs=-1,
)
baseline_model.fit(X_train_sm, y_train_sm)

y_pred_baseline = baseline_model.predict(X_test_s)
print("=== BASELINE (no leakage) ===")
print(classification_report(y_test, y_pred_baseline, target_names=label_encoder.classes_))
print("Macro F1:", f1_score(y_test, y_pred_baseline, average="macro"))
print("Accuracy:", accuracy_score(y_test, y_pred_baseline))

from sklearn.model_selection import train_test_split as tts

SEARCH_SAMPLE_SIZE = 300_000
if len(X_train_sm) > SEARCH_SAMPLE_SIZE:
    X_search, _, y_search, _ = tts(
        X_train_sm, y_train_sm,
        train_size=SEARCH_SAMPLE_SIZE,
        random_state=RANDOM_STATE,
        stratify=y_train_sm,
    )
else:
    X_search, y_search = X_train_sm, y_train_sm

print("Search subsample size:", X_search.shape)

param_dist = {
    "n_estimators": [200, 300, 400],
    "max_depth": [6, 8, 10],
    "learning_rate": [0.05, 0.1, 0.2],
    "subsample": [0.7, 0.8, 0.9],
    "colsample_bytree": [0.7, 0.8, 0.9],
    "min_child_weight": [1, 3, 5],
}

base_estimator = xgb.XGBClassifier(
    objective="multi:softprob",
    num_class=len(label_encoder.classes_),
    eval_metric="mlogloss",
    tree_method="hist",
    random_state=RANDOM_STATE,
    n_jobs=1,
)

search = RandomizedSearchCV(
    base_estimator,
    param_distributions=param_dist,
    n_iter=10,
    scoring="f1_macro",
    cv=2,
    verbose=2,
    random_state=RANDOM_STATE,
    n_jobs=-1,
)

print("Starting hyperparameter search...")
start = time.time()
search.fit(X_search, y_search)
elapsed = time.time() - start
print(f"Search finished in {elapsed/60:.1f} minutes")
print("Best params:", search.best_params_)

tuned_model = xgb.XGBClassifier(
    **search.best_params_,
    objective="multi:softprob",
    num_class=len(label_encoder.classes_),
    eval_metric="mlogloss",
    tree_method="hist",
    random_state=RANDOM_STATE,
    n_jobs=-1,
)
tuned_model.fit(X_train_sm, y_train_sm)

y_pred_tuned = tuned_model.predict(X_test_s)
print("=== TUNED (no leakage) ===")
print(classification_report(y_test, y_pred_tuned, target_names=label_encoder.classes_))
print("Macro F1:", f1_score(y_test, y_pred_tuned, average="macro"))
print("Accuracy:", accuracy_score(y_test, y_pred_tuned))

fig, ax = plt.subplots(figsize=(8, 7))
cm = confusion_matrix(y_test, y_pred_tuned)
ConfusionMatrixDisplay(confusion_matrix=cm, display_labels=label_encoder.classes_).plot(
    cmap="Blues", values_format="d", ax=ax, xticks_rotation=45)
plt.title("Confusion Matrix — XGBoost (No day_of_week/hour, tuned)")
plt.tight_layout()
plt.show()

