"""infilteration biased cheking threshold"""

import numpy as np
from sklearn.metrics import classification_report

infil_idx = list(le.classes_).index("Infilteration")

y_proba = xgb_final.predict_proba(X_test_scaled)

def predict_with_infil_threshold(y_proba, infil_idx, infil_min_conf):
    y_pred = np.argmax(y_proba, axis=1)
    # Wherever Infiltration was picked but its confidence is below the bar,
    # fall back to the second-best class instead
    infil_picked = (y_pred == infil_idx)
    low_conf = infil_picked & (y_proba[:, infil_idx] < infil_min_conf)
    if low_conf.any():
        proba_without_infil = y_proba.copy()
        proba_without_infil[:, infil_idx] = -1  # exclude Infiltration from the re-argmax
        y_pred[low_conf] = np.argmax(proba_without_infil[low_conf], axis=1)
    return y_pred

# Try a few thresholds and compare
for thresh in [0.5, 0.7, 0.85, 0.95]:
    y_pred_adj = predict_with_infil_threshold(y_proba, infil_idx, thresh)
