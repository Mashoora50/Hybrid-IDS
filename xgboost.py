"""clustering"""

import networkx as nx


G = nx.Graph()
G.add_nodes_from(numeric_cols)

threshold = 0.9
corr_matrix_full = corr_matrix.abs()

for col1 in numeric_cols:
    for col2 in numeric_cols:
        if col1 != col2 and corr_matrix_full.loc[col1, col2] > threshold:
            G.add_edge(col1, col2)


clusters = list(nx.connected_components(G))
redundant_clusters = [c for c in clusters if len(c) > 1]

print(f"Found {len(redundant_clusters)} clusters of correlated features:\n")
cols_to_drop = []
for cluster in redundant_clusters:
    cluster = list(cluster)
    keep = cluster[0]
    drop = cluster[1:]
    print(f"KEEP: {keep}  |  DROP: {drop}")
